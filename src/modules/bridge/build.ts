// Builds the Chrome extension each Chrome profile named in data/config.json chromeProfiles loads: copies the source next to a
// config.js holding the bridge address and key. Output: data/extension/ (gitignored, chmod 700).
//   npm run bridge:extension
import { chmodSync, copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { CHROME_DOMAINS, JIRA_HOST } from '../../config.ts'
import { BRIDGE_PORT, bridgeKey, EXTENSION_DIR } from './index.ts'

const src = join(import.meta.dirname, 'extension')
mkdirSync(EXTENSION_DIR, { recursive: true }); chmodSync(EXTENSION_DIR, 0o700)
copyFileSync(join(src, 'background.js'), join(EXTENSION_DIR, 'background.js'))
// the company's Jira comes from data/config.json (jiraHost), not from the shared source
const manifest = JSON.parse(readFileSync(join(src, 'manifest.json'), 'utf8'))
if (JIRA_HOST) manifest.host_permissions.push(`${JIRA_HOST}/*`)
writeFileSync(join(EXTENSION_DIR, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n')
const version = manifest.version
writeFileSync(join(EXTENSION_DIR, 'config.js'),
  `// generated by npm run bridge:extension: do not share\nexport const HUB = 'http://127.0.0.1:${BRIDGE_PORT}'\nexport const KEY = '${bridgeKey()}'\nexport const VERSION = '${version}'\nexport const JIRA = ${JSON.stringify(JIRA_HOST)}\nexport const DOMAINS = ${JSON.stringify(CHROME_DOMAINS)}\n`, { mode: 0o600 })
console.log(`Extension ở ${EXTENSION_DIR}. Trong từng Chrome profile khai ở chromeProfiles (data/config.json): chrome://extensions → Developer mode → Load unpacked → chọn thư mục này.`)
